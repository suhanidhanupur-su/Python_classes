
## Rules to declare a variable:

#1. A variable name must start with a letter or the underscore character "_".
# Example: _name, name, name1, name_1 etc.
#2. A variable name only contains letters, numbers and the underscore character "_".
#=> a variable name cannot contain spaces or special characters like !, @, #, $, %, ^, &, * etc.


first_name = "Ansh"
name_1 = "Ujwal"
print(first_name)
#3. A variable name is always case-sensitive.
#=> first_name and FIRST_NAME are two different variables.
#Except SQL(Structured Query Language)
#Ex: SELECT * FROM accounts_product;
 #language, all other programming languages are case-sensitive.

#4. Keywords are not allwowed to be used as variable names.

## Keywords: keywords are the words that are predefined in a programming language.
#Ex: print, if, else, elif, for, while, break, continue, def, return, import, as, from, in, is, not, and, or, lambda, with, try, except, finally, class, pass, raise, yield, global, nonlocal, assert, del
#5. A variable name always should be meaningful.
#Ex: first_name, last_name, age, roll_number, total_marks, average_marks etc



